#!/usr/bin/env python3
"""Generate ASCII-safe JS data files from the raw-Bengali JSON sources.

Reads tools/presets-source.json and tools/i18n-source.json (UTF-8 Bengali),
writes js/presets.js (window.PRESETS) and js/i18n.js (window.I18N) with
json.dumps(ensure_ascii=True) so the shipped JS is pure ASCII. This mirrors
the factory's ASCII-safety rule: the GitHub push path once corrupted raw
non-ASCII argv text, so app sources carry Bengali only as \\uXXXX escapes.

Run from the project root:  python3 tools/build-i18n.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    presets = json.loads((ROOT / "tools" / "presets-source.json").read_text(encoding="utf-8"))
    i18n = json.loads((ROOT / "tools" / "i18n-source.json").read_text(encoding="utf-8"))

    presets_js = (
        "// GENERATED by tools/build-i18n.py from tools/presets-source.json\n"
        "// Do not edit by hand. Bengali is stored as \\uXXXX escapes so this\n"
        "// file is pure ASCII (GitHub push argv safety). Source of truth:\n"
        "// tools/presets-source.json\n"
        "'use strict';\n"
        "window.PRESETS = "
        + json.dumps(presets["presets"], ensure_ascii=True, indent=2)
        + ";\n"
    )
    (ROOT / "js" / "presets.js").write_text(presets_js, encoding="ascii")

    i18n_js = (
        "// GENERATED by tools/build-i18n.py from tools/i18n-source.json\n"
        "// Do not edit by hand. Bengali is stored as \\uXXXX escapes so this\n"
        "// file is pure ASCII (GitHub push argv safety). Source of truth:\n"
        "// tools/i18n-source.json\n"
        "'use strict';\n"
        "window.I18N = "
        + json.dumps(i18n, ensure_ascii=True, indent=2)
        + ";\n"
    )
    (ROOT / "js" / "i18n.js").write_text(i18n_js, encoding="ascii")

    for name in ("js/presets.js", "js/i18n.js"):
        data = (ROOT / name).read_bytes()
        assert all(b < 128 for b in data), name + " is not pure ASCII"
    print("generated js/presets.js (%d presets) and js/i18n.js (%d keys), both pure ASCII"
          % (len(presets["presets"]), len(i18n)))


if __name__ == "__main__":
    sys.exit(main())
